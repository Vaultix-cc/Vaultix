def _upload_message(vectors, item, signed_at=None):
    return zk1.upload_message(vectors["appId"], item["kind"], item["productId"], item["name"], H(item["keyedHash"]),
                              item["plainLength"], item["signedAt"] if signed_at is None else signed_at)


def test_signature_block_vectors(vectors):
    app_id = vectors["appId"]
    sign_public = H(app0(vectors)["signPublic"])
    people = {p["userId"]: p for p in vectors["personal"]}
    certs = {c["userId"]: c for c in vectors["certs"]}
    for cert in vectors["certs"]:
        message = zk1.member_message(app_id, cert["userId"], H(cert["encPublic"]), H(cert["signPublic"]), cert["issuedAt"])
        assert message == H(cert["message"])
        assert zk1.ed25519_verify(sign_public, H(cert["signature"]), message)
    for item in vectors["files"]:
        assert _upload_message(vectors, item) == H(item["uploadMessage"])
        block = zk1.verify_signature_block(H(item["signature"]), app_id, sign_public,
                                           lambda at: _upload_message(vectors, item, at))
        assert block.signed_at_ms == item["signedAt"] and block.user_id == item["uploader"]
        # the test helper builds the same block
        person, cert = people[item["uploader"]], certs[item["uploader"]]
        rebuilt = signature_block(item["uploader"], H(person["encPublic"]), H(person["signPublic"]), cert["issuedAt"],
                                  H(cert["signature"]), item["signedAt"],
                                  ed25519_sign(H(person["signSeed"]), H(item["uploadMessage"])))
        assert rebuilt == H(item["signature"])


def test_signature_block_tampering_fails(vectors):
    app_id = vectors["appId"]
    sign_public = H(app0(vectors)["signPublic"])
    other_sign_public = H(vectors["appKeys"][1]["signPublic"])
    item = vectors["files"][0]
    raw = H(item["signature"])
    message_for = lambda at: _upload_message(vectors, item, at)  # noqa: E731
    id_len = int.from_bytes(raw[1:3], "big")
    cert_at = 3 + id_len + 32 + 32 + 8
    sig_at = cert_at + 64 + 8
    cases = {
        "user id": flip(raw, 3), "enc public key": flip(raw, 3 + id_len), "sign public key": flip(raw, 3 + id_len + 32),
        "issued at": flip(raw, cert_at - 1), "owner approval": flip(raw, cert_at), "signed at": flip(raw, sig_at - 1),
        "signature": flip(raw, sig_at), "last byte": flip(raw, len(raw) - 1), "version": flip(raw, 0, 0x02),
        "truncated": raw[:-1], "appended": raw + b"\x00", "empty": b"",
    }
    for what, data in cases.items():
        with pytest.raises(zk1.Zk1Error):
            zk1.verify_signature_block(data, app_id, sign_public, message_for)
    with pytest.raises(zk1.Zk1Error, match="not approved"):
        zk1.verify_signature_block(raw, app_id, other_sign_public, message_for)
    with pytest.raises(zk1.Zk1Error, match="not approved"):
        zk1.verify_signature_block(raw, "app-2", sign_public, message_for)
    for wrong in (lambda at: zk1.upload_message(app_id, item["kind"], "", item["name"], H(item["keyedHash"]),
                                                item["plainLength"], at),
                  lambda at: zk1.upload_message(app_id, item["kind"], item["productId"], item["name"],
                                                H(item["keyedHash"]), item["plainLength"] + 1, at),
                  lambda at: zk1.upload_message(app_id, item["kind"], item["productId"], "other.exe",
                                                H(item["keyedHash"]), item["plainLength"], at),
                  lambda at: zk1.upload_message(app_id, item["kind"], item["productId"], item["name"], bytes(32),
                                                item["plainLength"], at)):
        with pytest.raises(zk1.Zk1Error, match="invalid signature"):
            zk1.verify_signature_block(raw, app_id, sign_public, wrong)
    # a small-order "public key" is refused even with a trivial signature
    assert not zk1.ed25519_verify(bytes.fromhex("01" + "00" * 31), bytes(64), b"anything")


