def test_sdk_key_decode_hash_key_and_fingerprint(vectors):
    for app in vectors["appKeys"]:
        secret, sign_public = zk1.sdk_key_decode(app["sdkKey"])
        assert secret == H(app["sdkSecret"]) and sign_public == H(app["signPublic"])
        key = zk1.ContentKey.from_sdk_key(app["sdkKey"])
        assert key.hash_key == H(app["hashKey"])
        assert zk1.hash_key_from_sdk_secret(secret) == H(app["hashKey"])
        assert key.sdk_public == H(app["sdkPublic"])
        assert key.fingerprint == app["fingerprint"]
        assert zk1.fingerprint(H(app["sdkPublic"]), H(app["signPublic"])) == app["fingerprint"]
        assert len(app["sdkKey"]) == zk1.SDK_KEY_CHARS
        assert app["sdkKey"] not in repr(key) and app["sdkSecret"] not in repr(key)
        # surrounding whitespace is ignored, as in the C++ SDK
        assert zk1.sdk_key_decode("  \t" + app["sdkKey"] + "\r\n") == (secret, sign_public)


def test_sdk_key_rejects_every_change(vectors):
    sdk = app0(vectors)["sdkKey"]
    rejected = 0
    for i in range(4, len(sdk)):
        broken = sdk[:i] + ("B" if sdk[i] == "A" else "A") + sdk[i + 1:]
        try:
            zk1.sdk_key_decode(broken)
        except zk1.Zk1Error:
            rejected += 1
    assert rejected == 92
    secret = H(app0(vectors)["sdkSecret"])
    v1 = "vxk_" + zk1.b64u_encode(bytes([1]) + secret + hashlib.sha256(b"vaultix-vxk" + bytes([1]) + secret).digest()[:4])
    for bad in ["", "vxk_short", "vxx_" + sdk[4:], sdk + "A", sdk + "AAAA", sdk[:95], sdk[:92], sdk[4:],
                "VXK_" + sdk[4:], sdk[:30] + "+" + sdk[31:], sdk[:30] + "=" + sdk[31:], sdk[:50] + " " + sdk[50:], v1,
                None, 12345]:
        with pytest.raises(zk1.Zk1Error):
            zk1.sdk_key_decode(bad)


def test_keyed_hash(vectors):
    key = content_key(vectors)
    for item in vectors["files"]:
        assert zk1.keyed_hash(key.hash_key, H(item["plainSha256"])) == H(item["keyedHash"])
    for item in vectors["variables"]:
        digest = hashlib.sha256(item["value"].encode("utf-8")).digest()
        assert zk1.keyed_hash(key.hash_key, digest) == H(item["keyedHash"])


