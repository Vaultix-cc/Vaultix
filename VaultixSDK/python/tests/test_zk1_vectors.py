def test_unseal_vectors(vectors):
    secret = H(app0(vectors)["sdkSecret"])
    public = H(app0(vectors)["sdkPublic"])
    for item in vectors["seal"]:
        context = zk1.seal_context(item["kind"], item["name"], item["productId"])
        assert context == H(item["context"])
        assert zk1.unseal(secret, H(item["sealed"]), context) == H(item["payload"])
        # the test helper seals byte for byte like the browser
        assert seal(public, H(item["payload"]), context, H(item["ephSecret"])) == H(item["sealed"])


def test_unseal_refuses_other_context_key_and_tampering(vectors):
    secret = H(app0(vectors)["sdkSecret"])
    other = H(vectors["appKeys"][1]["sdkSecret"])
    item = vectors["seal"][2]  # file, product scope
    sealed = H(item["sealed"])
    context = H(item["context"])
    for wrong in (zk1.seal_context("file", item["name"], ""), zk1.seal_context("folder", item["name"], item["productId"]),
                  zk1.seal_context("var", item["name"], item["productId"]),
                  zk1.seal_context("file", item["name"] + " ", item["productId"]),
                  zk1.seal_context("file", item["name"], "prod-other")):
        with pytest.raises(zk1.Zk1Error):
            zk1.unseal(secret, sealed, wrong)
    with pytest.raises(zk1.Zk1Error):
        zk1.unseal(other, sealed, context)
    for pos in (0, 1, 20, 33, 60, len(sealed) - 1):
        with pytest.raises(zk1.Zk1Error):
            zk1.unseal(secret, flip(sealed, pos), context)
    with pytest.raises(zk1.Zk1Error):
        zk1.unseal(secret, sealed[:48], context)
    # a low-order ephemeral key gives an all-zero shared secret: refused
    with pytest.raises(zk1.Zk1Error):
        zk1.unseal(secret, sealed[:1] + bytes(32) + sealed[33:], context)


