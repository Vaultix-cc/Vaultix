def test_kat_primitives(vectors):
    kat = vectors["kat"]
    for item in kat["x25519"]:
        assert zk1.x25519_shared(H(item["scalar"]), H(item["u"])) == H(item["out"])
    for item in kat["x25519_public"]:
        assert zk1.x25519_public(H(item["scalar"])) == H(item["public"])
    for item in kat["hkdf"]:
        assert zk1.hkdf(H(item["ikm"]), H(item["salt"]), H(item["info"]), item["length"]) == H(item["okm"])
    for item in kat["ed25519"]:
        assert ed25519_public(H(item["seed"])) == H(item["public"])
        assert zk1.ed25519_verify(H(item["public"]), H(item["signature"]), H(item["message"]))
        assert not zk1.ed25519_verify(H(item["public"]), flip(H(item["signature"]), 0), H(item["message"]))
    for item in kat["hmac_sha256"]:
        assert hmac.new(H(item["key"]), H(item["data"]), hashlib.sha256).digest() == H(item["mac"])
    for item in kat["aes_gcm"]:
        sealed = H(item["ciphertext"]) + H(item["tag"])
        assert AESGCM(H(item["key"])).decrypt(H(item["nonce"]), sealed, H(item["aad"]) or None) == H(item["plaintext"])


