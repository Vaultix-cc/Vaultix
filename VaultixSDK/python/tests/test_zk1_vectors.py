"""The SDK-relevant parts of the shared zk1 vectors, byte for byte
(docs/E2EE_FORMAT.md; generated by backend/tests/zk1_reference.py)."""

import hashlib
import hmac

import pytest
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

from vaultix import zk1
from zk1_server import delivery, ed25519_public, ed25519_sign, pattern, seal, signature_block, stream_encrypt

H = bytes.fromhex


def flip(data: bytes, pos: int, mask: int = 0x01) -> bytes:
    out = bytearray(data)
    out[pos] ^= mask
    return bytes(out)


def app0(vectors):
    return vectors["appKeys"][0]


def content_key(vectors, index=0):
    return zk1.ContentKey.from_sdk_key(vectors["appKeys"][index]["sdkKey"])


