def test_stream_vectors(vectors):
    for item in vectors["stream"]:
        key = H(item["key"])
        plain = pattern(item["plainLength"], item["seed"])
        blob = stream_encrypt(key, plain, b"VXZ1")
        assert len(blob) == item["cipherLength"]
        assert hashlib.sha256(blob).hexdigest() == item["cipherSha256"]
        if "cipher" in item:
            assert blob == H(item["cipher"])
        data = zk1.stream_decrypt(key, blob, b"VXZ1")
        assert hashlib.sha256(data).hexdigest() == item["plainSha256"] and data == plain
        # incremental, in odd-sized pieces
        out = []
        decryptor = zk1.StreamDecryptor(key, b"VXZ1", lambda piece: out.append(piece) is None)
        for start in range(0, len(blob), 777_777):
            assert decryptor.update(blob[start:start + 777_777])
        assert decryptor.finish() and b"".join(out) == plain


def test_stream_truncated_flipped_reordered_fail(vectors):
    item = vectors["stream"][6]  # 2 chunks + 5 bytes
    key = H(item["key"])
    blob = stream_encrypt(key, pattern(item["plainLength"], item["seed"]), b"VXZ1")
    h, n = zk1.HEADER_BYTES, zk1.CHUNK_SIZE + zk1.TAG_BYTES
    header, c0, c1, c2 = blob[:h], blob[h:h + n], blob[h + n:h + 2 * n], blob[h + 2 * n:]
    bad = {
        "truncated by one byte": blob[:-1],
        "last tag cut off": blob[:-16],
        "truncated at a chunk boundary": header + c0 + c1,
        "truncated after the first chunk": header + c0,
        "reordered chunks": header + c1 + c0 + c2,
        "last two swapped": header + c0 + c2 + c1,
        "appended byte": blob + b"\x00",
        "appended chunk": blob + c2,
        "header only": header,
        "header + 15 bytes": header + bytes(15),
        "empty": b"",
        "read as a delivery": None,
    }
    for pos in (0, 4, 5, 8, 9, 100, h + n - 1, h + n, len(blob) // 2, len(blob) - 17, len(blob) - 1):
        bad[f"flipped bit at {pos}"] = flip(blob, pos)
    for what, data in bad.items():
        magic = b"VXZ1"
        if data is None:
            data, magic = blob, b"VXD1"
        released = []
        decryptor = zk1.StreamDecryptor(key, magic, lambda piece: released.append(piece) is None)
        assert not (decryptor.update(data) and decryptor.finish()), what
        assert decryptor.error, what
        with pytest.raises(zk1.Zk1Error):
            zk1.stream_decrypt(key, data, magic)
    with pytest.raises(zk1.Zk1Error):
        zk1.stream_decrypt(bytes(32), blob, b"VXZ1")
    # well-formed streams with another version or chunk size
    plain = pattern(1000, 1)
    for blob2 in (stream_encrypt(key, plain, b"VXZ1", version=2), stream_encrypt(key, plain, b"VXZ1", chunk_size=65536)):
        with pytest.raises(zk1.Zk1Error):
            zk1.stream_decrypt(key, blob2, b"VXZ1")
    empty = stream_encrypt(key, b"", b"VXZ1")
    assert len(empty) == 25 and zk1.stream_decrypt(key, empty, b"VXZ1") == b""
    with pytest.raises(zk1.Zk1Error):
        zk1.stream_decrypt(key, empty[:24], b"VXZ1")


