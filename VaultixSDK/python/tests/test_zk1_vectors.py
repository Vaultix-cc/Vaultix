def test_delivery_opener_file_incremental(vectors):
    """What the client does with a file delivery, fed in uneven pieces."""
    item = vectors["delivery"][0]
    file_vec = vectors["files"][0]
    body = H(item["body"])
    for piece in (1, 7, 100, 4096, len(body)):
        out = []
        opener = zk1.DeliveryOpener(H(item["clientSecret"]), "file")
        opener.set_file_context(content_key(vectors), vectors["appId"], file_vec["name"], file_vec["productId"],
                                lambda data: out.append(data) is None)
        assert opener.begin(item["header"]), opener.error
        for start in range(0, len(body), piece):
            assert opener.update(body[start:start + piece]), opener.error
        assert opener.finish(), opener.error
        assert b"".join(out) == pattern(file_vec["plainLength"], file_vec["seed"])
        assert opener.signed_at == file_vec["signedAt"] and opener.scope == file_vec["productId"]
        assert opener.content_size == file_vec["plainLength"]
    # wrong content key, another name, or a wrong client key: nothing is released
    for key, name, secret in ((content_key(vectors, 1), file_vec["name"], H(item["clientSecret"])),
                              (content_key(vectors), "other.exe", H(item["clientSecret"])),
                              (content_key(vectors), file_vec["name"], H(vectors["delivery"][1]["clientSecret"]))):
        out = []
        opener = zk1.DeliveryOpener(secret, "file")
        opener.set_file_context(key, vectors["appId"], name, file_vec["productId"], lambda data: out.append(data) is None)
        assert not (opener.begin(item["header"]) and opener.update(body) and opener.finish())
        assert out == [] and opener.error


def test_delivery_opener_vars_and_open_variables(vectors):
    item = vectors["delivery"][1]
    opener = zk1.DeliveryOpener(H(item["clientSecret"]), "vars")
    assert opener.begin(item["header"]) and opener.update(H(item["body"])) and opener.finish(), opener.error
    assert opener.object_id == "prod-1234"
    values = zk1.open_variables(opener.vars_payload, content_key(vectors), vectors["appId"], "prod-1234")
    assert values == [("apiUrl", vectors["variables"][0]["value"]), ("legacy", "plain")]
    # without a content key, with the wrong key or for another product: nothing
    with pytest.raises(zk1.Zk1Error, match="set_content_key"):
        zk1.open_variables(opener.vars_payload, None, vectors["appId"], "prod-1234")
    with pytest.raises(zk1.Zk1Error, match="cannot open variable"):
        zk1.open_variables(opener.vars_payload, content_key(vectors, 1), vectors["appId"], "prod-1234")
    with pytest.raises(zk1.Zk1Error):
        zk1.open_variables(opener.vars_payload, content_key(vectors), vectors["appId"], "prod-other")
    with pytest.raises(zk1.Zk1Error, match="signature check failed"):
        zk1.open_variables(opener.vars_payload, content_key(vectors), "app-2", "prod-1234")
    for bad in (b"{}", b"[1]", b'[{"value":"x"}]', b'[{"name":"a","name":"b"}]', b'[{"name":null}]',
                b'[{"name":"a","enc":"zk2","value":"x"}]', b"[", b"[] x", b'[{"name":"a","value":NaN}]',
                b'[{"name":"\\ud800"}]', b'[{"name":"a","value":5}]'):
        with pytest.raises(zk1.Zk1Error):
            zk1.open_variables(bad, content_key(vectors), vectors["appId"], "prod-1234")
