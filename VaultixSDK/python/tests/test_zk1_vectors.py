def _file_blob(item):
    if "cipher" in item:
        return H(item["cipher"])
    blob = stream_encrypt(H(item["fileKey"]), pattern(item["plainLength"], item["seed"]), b"VXZ1")
    assert hashlib.sha256(blob).hexdigest() == item["cipherSha256"]
    return blob


def test_sdk_open_file_vectors(vectors):
    key = content_key(vectors)
    app_id = vectors["appId"]
    for item in vectors["files"]:
        blob = _file_blob(item)
        assert len(blob) == item["cipherLength"]
        data, signed_at = zk1.sdk_open_file(key, app_id, item["kind"], item["name"], item["productId"],
                                            H(item["sealed"]), H(item["signature"]), blob)
        assert data == pattern(item["plainLength"], item["seed"]) and signed_at == item["signedAt"]
        assert hashlib.sha256(data).hexdigest() == item["plainSha256"]


def test_sdk_open_file_scopes_and_failures(vectors):
    key = content_key(vectors)
    app_id = vectors["appId"]
    general = vectors["files"][2]   # file "empty.bin", general scope ""
    product = vectors["files"][0]   # file "loader.exe", product "prod-1234"
    # a general file requested for any product opens with the general scope
    data, _ = zk1.sdk_open_file(key, app_id, "file", general["name"], "prod-anything", H(general["sealed"]),
                                H(general["signature"]), _file_blob(general))
    assert data == b""
    # a product file requested as general, or for another product, fails
    for product_id in ("", "prod-other"):
        with pytest.raises(zk1.Zk1Error):
            zk1.sdk_open_file(key, app_id, "file", product["name"], product_id, H(product["sealed"]),
                              H(product["signature"]), _file_blob(product))
    blob = _file_blob(product)
    args = (app_id, "file", product["name"], product["productId"], H(product["sealed"]), H(product["signature"]))
    for bad_key in (vectors["appKeys"][1]["sdkKey"],):
        with pytest.raises(zk1.Zk1Error):
            zk1.sdk_open_file(bad_key, *args, blob)
    for bad_blob in (blob[:-1], flip(blob, 40), blob + b"\x00"):
        with pytest.raises(zk1.Zk1Error):
            zk1.sdk_open_file(key, *args, bad_blob)
    with pytest.raises(zk1.Zk1Error):  # a folder key is not a file key
        zk1.sdk_open_file(key, app_id, "folder", product["name"], product["productId"], H(product["sealed"]),
                          H(product["signature"]), blob)


