def _delivery_body(item):
    if "body" in item:
        return H(item["body"])
    payload = pattern(item["payloadPattern"]["length"], item["payloadPattern"]["seed"])
    header, body = delivery(zk1.x25519_public(H(item["clientSecret"])), item["kind"], item["objectId"], payload,
                            H(item["serverSecret"]))
    assert header == item["header"] and hashlib.sha256(body).hexdigest() == item["bodySha256"]
    return body


def test_delivery_vectors(vectors):
    for item in vectors["delivery"]:
        secret = H(item["clientSecret"])
        assert zk1.b64u_encode(zk1.x25519_public(secret)) == item["clientPublicB64u"]
        body = _delivery_body(item)
        assert len(body) == item["bodyLength"]
        kind, object_id, payload = zk1.open_delivery(secret, item["header"], body, expected_kind=item["kind"])
        assert (kind, object_id) == (item["kind"], item["objectId"])
        assert len(payload) == item["payloadLength"] and hashlib.sha256(payload).hexdigest() == item["payloadSha256"]
        if "payload" in item:
            assert payload == H(item["payload"])
            # the test helper produces the same body
            header, rebuilt = delivery(zk1.x25519_public(secret), kind, object_id, payload, H(item["serverSecret"]))
            assert (header, rebuilt) == (item["header"], body)


